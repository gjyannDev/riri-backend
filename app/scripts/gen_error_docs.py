"""Generate docs/error-codes.md from the error classes.

Run: uv run python -m app.scripts.gen_error_docs
A test fails when the committed page differs from what this script generates.
"""

import importlib
import pkgutil
from pathlib import Path

import app.modules
from app.core.errors import error_classes

DOC_PATH = Path(__file__).resolve().parents[2] / "docs" / "error-codes.md"

HEADER = """# Error codes

Generated by `uv run python -m app.scripts.gen_error_docs` from the classes in `app/core/errors/`
and each feature's `errors.py`. Do not edit by hand.

Every error response is `application/problem+json` with `type`, `title`, `status`, optional
`detail`, and these fields: `code` (stable; clients branch on it), `category`, `retryable`
and `request_id`. Renaming or removing a code is a breaking change.

| Code | Category | Status | Retryable | Meaning | Class |
| --- | --- | --- | --- | --- | --- |
"""


def _import_feature_errors() -> None:
    """Import every `app/modules/<feature>/errors.py` so its classes are listed."""
    for module in pkgutil.walk_packages(app.modules.__path__, f"{app.modules.__name__}."):
        if module.name.endswith(".errors"):
            importlib.import_module(module.name)


def render() -> str:
    _import_feature_errors()
    rows = [
        f"| `{cls.code}` | {cls.category.value} | {cls.status} | "
        f"{'yes' if cls.retryable else 'no'} | {cls.title} | `{cls.__name__}` |"
        for cls in error_classes()
    ]
    return HEADER + "\n".join(rows) + "\n"


def main() -> None:
    DOC_PATH.write_text(render(), encoding="utf-8")
    print(f"Wrote {DOC_PATH}")


if __name__ == "__main__":
    main()
